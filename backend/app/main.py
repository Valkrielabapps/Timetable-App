@app.on_event("startup")
def _start_outreach_sender():
    """The sales outreach sender (app/services/outreach.py) runs in the
    background while the server is up. It sends nothing until a mailbox is
    connected and sending is switched on in the admin page. Not started under
    the test suite, which drives it directly."""
    import sys

    if "pytest" in sys.modules:
        return
    from app.core.database import SessionLocal
    from app.services.outreach import start_scheduler

    start_scheduler(SessionLocal)


@app.get("/health")
def health_check():
    """Basic liveness check used by hosting platforms (Railway/Render)."""
    return {"status": "ok"}


@app.get("/api/version")
def version():
    """Which commit is live. Railway sets RAILWAY_GIT_COMMIT_SHA on every
    deploy, so this answers "is my push actually running yet?" at a glance."""
    import os
    sha = os.environ.get("RAILWAY_GIT_COMMIT_SHA") or "unknown"
    return {"commit": sha[:7]}
