"""
Exporting timetables to Excel and PDF.

There were no tests for exports before elective blocks, and adding the
per-student export meant refactoring the shared renderer - so the existing
whole-school export is covered here too, reading the generated files rather
than only their status codes. A test that checks for a 200 passes just as well
for a spreadsheet with the wrong lessons in it.

Student timetables: a student's timetable is the section's, filtered to the
common subjects plus only the option they chose from each block. No extra
solving - the section's timetable already holds every combination at once.
"""
import io
import itertools

import openpyxl
import pytest

from app.core.database import SessionLocal
from app.models.school import (
    ClassGroup, ElectiveBlock, ElectiveOption, Period, Subject, Teacher, Timetable,
    TimetableEntry,
)
from app.services.student_combinations import MAX_COMBINATIONS
from tests.conftest import create_school, signup


@pytest.fixture
def world(client):
    """11A over one day: two blocks and English, generated by hand so every
    cell is known.

      period 1: Block 1 - Physics (Rao) / Accounts (Khan)
      period 2: English (Verma)
      period 3: Block 2 - Chemistry (Das) / Economics (Nair) / Biology (Iyer)
    """
    _, headers = signup(client)
    school = create_school(client, headers)
    db = SessionLocal()
    try:
        sid = school["id"]
        periods = [Period(school_id=sid, day_of_week=0, order=o) for o in range(3)]
        subjects = {n: Subject(school_id=sid, name=n) for n in
                    ("Physics", "Accounts", "English", "Chemistry", "Economics", "Biology")}
        teachers = {n: Teacher(school_id=sid, name=n, qualified_subject_ids=[])
                    for n in ("Rao", "Khan", "Verma", "Das", "Nair", "Iyer")}
        a = ClassGroup(school_id=sid, grade="Grade 11", name="A")
        plain = ClassGroup(school_id=sid, grade="Grade 9", name="A")
        db.add_all([*periods, *subjects.values(), *teachers.values(), a, plain])
        db.commit()
        b1 = ElectiveBlock(school_id=sid, class_group_id=a.id, name="Block 1", periods_per_week=1,
                           options=[ElectiveOption(subject_id=subjects[n].id) for n in ("Physics", "Accounts")])
        b2 = ElectiveBlock(school_id=sid, class_group_id=a.id, name="Block 2", periods_per_week=1,
                           options=[ElectiveOption(subject_id=subjects[n].id)
                                    for n in ("Chemistry", "Economics", "Biology")])
        db.add_all([b1, b2])
        tt = Timetable(school_id=sid, status="draft", solver_status="optimal")
        db.add(tt)
        db.commit()
        rows = [
            ("Physics", "Rao", 0, b1), ("Accounts", "Khan", 0, b1),
            ("English", "Verma", 1, None),
            ("Chemistry", "Das", 2, b2), ("Economics", "Nair", 2, b2), ("Biology", "Iyer", 2, b2),
        ]
        for subject, teacher, period, block in rows:
            db.add(TimetableEntry(
                timetable_id=tt.id, class_group_id=a.id, subject_id=subjects[subject].id,
                teacher_id=teachers[teacher].id, period_id=periods[period].id,
                elective_block_id=block.id if block else None,
            ))
        db.commit()
        ids = {"tt": tt.id, "a": a.id, "plain": plain.id, "school": sid}
    finally:
        db.close()
    return ids, headers


def _export(client, w, headers, **params):
    query = "&".join(f"{k}={v}" for k, v in params.items())
    return client.get(f"/api/timetables/{w['tt']}/export?{query}", headers=headers)


def _sheets(content: bytes) -> dict[str, list[list]]:
    wb = openpyxl.load_workbook(io.BytesIO(content))
    return {ws.title: [[c.value for c in row] for row in ws.iter_rows()] for ws in wb.worksheets}


def _text(rows) -> str:
    return "\n".join(str(v) for row in rows for v in row if v)


