def test_the_school_export_has_a_sheet_per_section_and_per_teacher(client, world):
    w, h = world
    r = _export(client, w, h, format="xlsx")
    assert r.status_code == 200, r.text
    sheets = _sheets(r.content)
    assert "Grade 11 - A" in sheets
    assert {"Rao", "Khan", "Verma", "Das", "Nair", "Iyer"} <= set(sheets)


def test_a_section_with_nothing_scheduled_gets_no_sheet(client, world):
    w, h = world
    assert "Grade 9 - A" not in _sheets(_export(client, w, h, format="xlsx").content)


def test_the_section_sheet_shows_every_option_under_its_block_name(client, world):
    """One cell with three subjects in it needs to say why."""
    w, h = world
