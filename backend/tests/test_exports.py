def test_a_section_from_another_school_is_refused(client, world):
    w, h = world
    _, other = signup(client, email="other@else.com")
    other_school = create_school(client, other)
    foreign = client.post("/api/class-groups", json={"school_id": other_school["id"], "name": "Z"},
                          headers=other).json()["id"]
    r = _export(client, w, h, format="xlsx", class_group_id=foreign, student_combinations="true")
    assert r.status_code == 404


def test_an_absurd_number_of_combinations_is_refused_with_a_reason(client, world):
    """Past the cap the request is almost certainly a data-entry mistake, and
    producing it would look like the export had hung."""
    w, h = world
    db = SessionLocal()
    try:
        # Enough single-subject-pair blocks to exceed the cap: 2^10 = 1024.
        for i in range(10):
            a = Subject(school_id=w["school"], name=f"X{i}")
            b = Subject(school_id=w["school"], name=f"Y{i}")
            db.add_all([a, b])
            db.commit()
            db.add(ElectiveBlock(school_id=w["school"], class_group_id=w["a"], name=f"Extra {i}",
                                 periods_per_week=1,
                                 options=[ElectiveOption(subject_id=a.id), ElectiveOption(subject_id=b.id)]))
        db.commit()
    finally:
        db.close()
    assert 6 * 2 ** 10 > MAX_COMBINATIONS
    r = _export(client, w, h, format="xlsx", class_group_id=w["a"], student_combinations="true")
    assert r.status_code == 400
    assert "combinations" in r.json()["detail"]
